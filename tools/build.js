'use strict';
const fs = require('node:fs');
const path = require('node:path');
const ROOT = __dirname;
const TARGETS = [{ source: 'src/audits/products-attributes-locale-audit.js', output: 'audits/products-attributes-locale-audit.js' }];
const MODULES = { progress: 'runtime/progress.js', adaptive: 'runtime/adaptive.js' };
const HEADER = "/* AUTO-GENERATED by node tools/build.js. Edit tools/src/audits/products-attributes-locale-audit.js and tools/runtime/*.js. */\n";
function assemble(target) {
  let code = fs.readFileSync(path.join(ROOT, target.source), 'utf8');
  for (const [name, file] of Object.entries(MODULES)) {
    const marker = '/* @runtime ' + name + ' */';
    if (code.split(marker).length !== 2) throw new Error('Ожидается один маркер ' + marker + ' в ' + target.source);
    code = code.replace(marker, fs.readFileSync(path.join(ROOT, file), 'utf8').trimEnd());
  }
  if (code.includes('/* @runtime ')) throw new Error('Неизвестный runtime marker');
  return HEADER + code;
}
let outdated = false;
const check = process.argv.includes('--check');
for (const target of TARGETS) {
  const destination = path.join(ROOT, target.output);
  const expected = assemble(target);
  const actual = fs.existsSync(destination) ? fs.readFileSync(destination, 'utf8') : null;
  if (check) {
    if (actual !== expected) { console.error('OUTDATED:', target.output); outdated = true; }
    else console.log('OK:', target.output);
  } else {
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, expected);
    console.log('BUILT:', target.output);
  }
}
if (outdated) process.exitCode = 1;
